def skill_for(r, st):
    ldr,war,int_,pol,chr_ = st
    if war>=90: return r.choice(['맹돌','파진'])
    if int_>=90: return r.choice(['풍계','이간','위장'])
    if war>=80: return r.choice(['격전','신궁','파성'])
    if int_>=80: return r.choice(['미끼','이간','귀납'])
    if pol>=85: return r.choice(['부농','통상'])
    if chr_>=85: return r.choice(['명성','등용'])
    if ldr>=85: return r.choice(['훈련','수성','완강'])
    return r.choice(['','','','','치안','질풍','신행','강직'])

GRADES = ['C','B','A','S']
def apts_for(r, st):
    ldr,war,int_,pol,chr_ = st
    apt = [0,0,0,0,0,0]  # 창 극 노 기 병기 수군
    if war>=85:
        for i in r.sample([0,1,3], 2): apt[i]=3
    elif war>=70: apt[r.choice([0,1,3])]=2
    if int_>=85: apt[r.choice([2,4])]=max(apt[r.choice([2,4])],2)
    if ldr>=85 and war<70: apt[r.randint(0,3)]=2
    if r.random()<0.25: apt[r.randrange(6)]=max(apt[r.randrange(6)],1)
    return [GRADES[a] for a in apt]

